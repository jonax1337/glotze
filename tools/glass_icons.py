"""Wandelt Framework7 Icons in die Vektorgrafiken des Designs „Glas“ um (res/drawable/glass_ic_*.xml).

Aufruf: python tools/glass_icons.py <svg-Ordner> <res/drawable>
Quelle (MIT-Lizenz): https://www.npmjs.com/package/framework7-icons, Ordner package/svg.
Framework7 Icons sind im Stil der SF Symbols gezeichnet; die SF Symbols selbst dürfen nur auf
Apple-Plattformen verwendet werden.
Benötigt fontTools (nur Entwicklungswerkzeug, keine Laufzeitabhängigkeit).
"""
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path

SVG = "{http://www.w3.org/2000/svg}"
# Framework7 places its glyphs anywhere in their box, so each one is measured and centred in a
# 24 unit icon, its longer side as long as the Material icons of Soft Solid.
VIEWPORT = 24
LONGER_SIDE = 19
# Glyphs that sit beside text rather than on an icon tile.
SMALLER = {"chevron": 12}
# Our icon name -> Framework7 glyph.
GLYPHS = {
    "accessibility": "person_alt_circle_fill",
    "account": "person_crop_circle_fill",
    "apps": "square_grid_2x2_fill",
    "backup": "archivebox_fill",
    "bell": "bell_fill",
    "bluetooth": "gamecontroller_fill",
    "chevron": "chevron_right",
    "display": "tv_fill",
    "ethernet": "link",
    "hidden": "eye_slash_fill",
    "info": "info_circle_fill",
    "moon": "moon_fill",
    "network": "wifi",
    "palette": "paintbrush_fill",
    "place": "location_fill",
    "play": "play_fill",
    "settings": "gear_alt_fill",
    "shield": "lock_shield_fill",
    "sort": "arrow_up_arrow_down",
    "sound": "speaker_2_fill",
    "speaker": "hifispeaker_fill",
    "timer": "timer_fill",
    "tune": "slider_horizontal_3",
    "wifi_off": "wifi_slash",
}


def paths_of(svg_file):
    paths = []
    for element in ElementTree.parse(svg_file).getroot():
        if element.tag != SVG + "path":
            raise ValueError(f"{svg_file}: only <path> is supported, found {element.tag}")
        paths.append(element)
    return paths


def bounds_of(paths):
    pen = BoundsPen(None)
    for path in paths:
        parse_path(path.get("d"), pen)
    return pen.bounds


def centring(bounds, longer_side):
    """The scale and offset that put the glyph's outline in the middle of the icon."""
    left, top, right, bottom = bounds
    scale = longer_side / max(right - left, bottom - top)
    offset_x = (VIEWPORT - (right - left) * scale) / 2 - left * scale
    offset_y = (VIEWPORT - (bottom - top) * scale) / 2 - top * scale
    return scale, offset_x, offset_y


def vector_for(svg_file, longer_side):
    paths = paths_of(svg_file)
    scale, offset_x, offset_y = centring(bounds_of(paths), longer_side)
    drawn = []
    for path in paths:
        fill_type = ' android:fillType="evenOdd"' if path.get("fill-rule") == "evenodd" else ""
        drawn.append(f'        <path android:fillColor="@android:color/white"{fill_type}\n'
                     f'            android:pathData="{path.get("d")}" />')
    return (f'<?xml version="1.0" encoding="utf-8"?>\n'
            f'<!-- Generated by tools/glass_icons.py from Framework7 Icons ({svg_file.stem}, MIT). -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="24dp"\n'
            f'    android:height="24dp"\n'
            f'    android:viewportWidth="{VIEWPORT}"\n'
            f'    android:viewportHeight="{VIEWPORT}">\n'
            f'    <group\n'
            f'        android:scaleX="{scale:.5f}"\n'
            f'        android:scaleY="{scale:.5f}"\n'
            f'        android:translateX="{offset_x:.4f}"\n'
            f'        android:translateY="{offset_y:.4f}">\n'
            + "\n".join(drawn) +
            f'\n    </group>\n'
            f'</vector>\n')


def main(svg_dir, drawable_dir):
    for name, glyph in GLYPHS.items():
        vector = vector_for(Path(svg_dir) / f"{glyph}.svg", SMALLER.get(name, LONGER_SIDE))
        Path(drawable_dir, f"glass_ic_{name}.xml").write_text(vector, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
